#!/usr/bin/env python3
"""Generates crates/filter/src/labels.rs from Wireshark's value strings.

Wireshark filters accept the label of a value instead of the number, case-insensitively:
`ip.proto == "TCP"`, `icmp.type == "Echo (ping) request"`, `ip.flags.df == "Set"`. The labels
must match Wireshark's text exactly, so they come from `tshark -G values` for every Wireshark
field in crates/filter/src/fields.rs.

Run it again after adding fields, with tshark 4.6 or later on the PATH:

    python3 scripts/gen_labels.py
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ROOT / "crates/filter/src/fields.rs"
OUT = ROOT / "crates/filter/src/labels.rs"

# Fields with several value-string tables (picked at run time by a Wireshark preference): the
# index of the table that Wireshark uses by default.
TABLE = {
    # The `vlan.priority_drop` preference; the default is IEEE 802.1D-2004.
    "vlan.priority": 1,
}


def wireshark_fields():
    """(name, Field variant) of every Wireshark field in fields.rs."""
    rows = re.findall(r'^\s*(\w+): "([^"]+)", [^,]+(?:\([^)]*\))?, Wireshark,', FIELDS.read_text(), re.M)
    return [(name, variant) for variant, name in rows]


def tshark_values():
    out = subprocess.run(["tshark", "-G", "values"], capture_output=True, text=True, check=True).stdout
    version = subprocess.run(["tshark", "--version"], capture_output=True, text=True, check=True)
    return out, version.stdout.splitlines()[0]


def tables(lines):
    """The label tables of a field: a new table starts where a value repeats."""
    out, cur, seen = [], [], set()
    for value, label in lines:
        if value in seen:
            out.append(cur)
            cur, seen = [], set()
        cur.append((label, value))
        seen.add(value)
    if cur:
        out.append(cur)
    return out


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    fields = wireshark_fields()
    names = {n for n, _ in fields}
    values, version = tshark_values()
    numeric, boolean = {}, {}
    for line in values.splitlines():
        cols = line.split("\t")
        if len(cols) == 4 and cols[0] in ("V", "V64") and cols[1] in names:
            numeric.setdefault(cols[1], []).append((int(cols[2], 0), cols[3]))
        elif len(cols) == 4 and cols[0] == "T" and cols[1] in names:
            boolean[cols[1]] = [(cols[2], 1), (cols[3], 0)]

    chosen = {}
    for name, lines in numeric.items():
        t = tables(lines)
        if len(t) > 1 and name not in TABLE:
            sys.exit(f"{name} has {len(t)} value-string tables: add it to TABLE")
        chosen[name] = t[TABLE.get(name, 0)]
    chosen.update(boolean)

    consts, arms = {}, []
    for name, variant in fields:
        if name not in chosen:
            continue
        body = tuple(chosen[name])
        if name in boolean:
            const = "BOOL_" + re.sub(r"\W+", "_", body[0][0]).upper()
        else:
            const = re.sub(r"\W", "_", name).upper()
        const = consts.setdefault(body, const)
        arms.append((variant, const))

    out = [
        f"//! Wireshark's value-string labels, generated by `scripts/gen_labels.py` from `tshark -G values`",
        f"//! ({version}). Do not edit by hand.",
        "//!",
        "//! The labels are Wireshark's text (Wireshark is GPL-2.0-or-later); filters accept them in place",
        "//! of numbers, case-insensitively, as Wireshark does. Boolean fields map their labels to 1 and 0.",
        "",
        "use crate::fields::Field;",
        "",
        "/// The `(label, value)` pairs of a field, in Wireshark's order; empty when it has none.",
        "pub(crate) fn labels(f: Field) -> &'static [(&'static str, u64)] {",
        "    match f {",
    ]
    for variant, const in arms:
        out.append(f"        Field::{variant} => {const},")
    out += ["        _ => &[],", "    }", "}", ""]
    for body, const in consts.items():
        out.append(f"const {const}: &[(&str, u64)] = &[")
        out += [f"    ({rust_str(label)}, {value})," for label, value in body]
        out += ["];", ""]
    OUT.write_text("\n".join(out))
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    total = sum(len(b) for b in consts)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(arms)} fields, {len(consts)} tables, {total} labels")


if __name__ == "__main__":
    main()
