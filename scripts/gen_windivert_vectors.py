#!/usr/bin/env python3
"""Generate crates/filter/src/tests/windivert_vectors.rs from ebpfdivert's copy of WinDivert's
filter test vectors (tests/wd_vectors.c, itself generated from WinDivert 2.2's test/test_data.c
and test/test.c).

Usage: python3 scripts/gen_windivert_vectors.py [path/to/wd_vectors.c]

The default input is ../ebpfdivert/tests/wd_vectors.c. The vectors are WinDivert's, under its
LGPL-3.0-or-later / GPL-2.0-or-later dual license, compatible with Avulse's.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT.parent / "ebpfdivert" / "tests" / "wd_vectors.c"
OUT = ROOT / "crates" / "filter" / "src" / "tests" / "windivert_vectors.rs"


def tokens(src):
    """C tokens: strings (unescaped), identifiers, numbers and punctuation; comments dropped."""
    i = 0
    while i < len(src):
        c = src[i]
        if src.startswith("//", i):
            i = src.index("\n", i)
        elif src.startswith("/*", i):
            i = src.index("*/", i) + 2
        elif c == '"':
            j, out = i + 1, []
            while src[j] != '"':
                if src[j] == "\\":
                    nxt = src[j + 1]
                    out.append({"n": "\n", "t": "\t", "\\": "\\", '"': '"'}[nxt])
                    j += 2
                else:
                    out.append(src[j])
                    j += 1
            yield ("str", "".join(out))
            i = j + 1
        elif c.isalnum() or c == "_":
            j = i
            while j < len(src) and (src[j].isalnum() or src[j] == "_"):
                j += 1
            yield ("word", src[i:j])
            i = j
        elif c.isspace():
            i += 1
        else:
            yield ("punct", c)
            i += 1


def parse(src):
    toks = list(tokens(src))
    arrays, packets, tests = {}, {}, []
    i = 0
    while i < len(toks):
        kind, val = toks[i]
        # static const unsigned char NAME[] = { bytes };
        if val == "char" and toks[i + 2] == ("punct", "["):
            name = toks[i + 1][1]
            j = i + 6
            data = []
            while toks[j] != ("punct", "}"):
                if toks[j][0] == "word":
                    data.append(int(toks[j][1], 0))
                j += 1
            arrays[name] = bytes(data)
            i = j
        # static const struct packet pkt_NAME = { array, sizeof(array), "name" };
        elif val == "packet" and toks[i + 1][1].startswith("pkt_"):
            name = toks[i + 1][1]
            array = toks[i + 4][1]
            packets[name] = array
            i += 5
        # static const struct test tests[] = { {"filter" "...", &pkt_x, TRUE}, ... };
        elif val == "tests" and toks[i + 1] == ("punct", "["):
            j = i + 5
            while toks[j] != ("punct", "}") or toks[j + 1] != ("punct", ";"):
                if toks[j] == ("punct", "{"):
                    j += 1
                    filt = ""
                    while toks[j][0] == "str":
                        filt += toks[j][1]
                        j += 1
                    assert toks[j] == ("punct", ",") and toks[j + 1] == ("punct", "&"), toks[j]
                    pkt = toks[j + 2][1]
                    match = toks[j + 4][1]
                    tests.append((filt, pkt, match == "TRUE"))
                    j += 5
                j += 1
            i = j
        i += 1
    return arrays, packets, tests


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    src = path.read_text()
    arrays, packets, tests = parse(src)
    names = list(packets)
    out = [
        "//! WinDivert's filter test vectors, from WinDivert 2.2 (`test/test_data.c` and `test/test.c`)",
        "//! through ebpfdivert's `tests/wd_vectors.c`. The data is WinDivert's, under its",
        "//! LGPL-3.0-or-later / GPL-2.0-or-later dual license.",
        "//!",
        "//! Generated by `scripts/gen_windivert_vectors.py`. Do not edit.",
        "",
        "/// The packets: name and bytes (IP level).",
        "pub(super) const PACKETS: &[(&str, &[u8])] = &[",
    ]
    for n in names:
        data = arrays[packets[n]]
        out.append(f'    ("{n[4:]}", &[')
        for k in range(0, len(data), 16):
            out.append("        " + ", ".join(f"0x{b:02x}" for b in data[k : k + 16]) + ",")
        out.append("    ]),")
    out += [
        "];",
        "",
        "/// The tests: filter, index in [`PACKETS`], whether it matches.",
        "pub(super) const VECTORS: &[(&str, usize, bool)] = &[",
    ]
    for filt, pkt, match in tests:
        lit = filt.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    ("{lit}", {names.index(pkt)}, {"true" if match else "false"}),')
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(names)} packets, {len(tests)} vectors -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
